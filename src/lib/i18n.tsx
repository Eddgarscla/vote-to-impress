type I18nValue = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: CopyKey) => string;
  founderLabel: (id: string) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function announce(message: string) {
  if (typeof window === "undefined" || !message) return;
  window.dispatchEvent(new CustomEvent("vti-toast", { detail: message }));
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    const saved = window.localStorage.getItem("vti.lang");
    if (saved === "es" || saved === "en") setLangState(saved);
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang === "es" ? "es" : "en";
  }, [lang]);
  const value = useMemo<I18nValue>(() => ({
    lang,
    setLang: (next) => {
      setLangState(next);
      window.localStorage.setItem("vti.lang", next);
    },
    t: (key) => copy[lang][key],
    founderLabel: (id) => founderLabels[lang][id] ?? id,
  }), [lang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) {
    return {
      lang: "en",
      setLang: () => undefined,
      t: (key) => copy.en[key],
      founderLabel: (id) => founderLabels.en[id] ?? id,
    };
  }
  return value;
}
